    const SHAPES_TEST: &str = r##"#![allow(clippy::unwrap_used)]
use std::sync::Arc;

use bind_codegen_snapshots::bind_runtime::{AppError, Ctx, Int};
use bind_codegen_snapshots::{adt, arithmetic, control, lambdas, records};

fn json<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).unwrap()
}

fn leaf() -> Box<adt::Arvore> {
    Box::new(adt::Arvore::Folha)
}

#[test]
fn wire_shapes() {
    let ponto = adt::Ponto { x: Int::from_i64(1), r#type: "a".to_string() };
    assert_eq!(json(&ponto), r#"{"x":"1","type":"a"}"#);
    let back: adt::Ponto = serde_json::from_str(r#"{"x":"1","type":"a"}"#).unwrap();
    assert_eq!(back, ponto);
    assert_eq!(json(&adt::Arvore::Folha), r#""folha""#);
    let node = adt::Arvore::No { esq: leaf(), valor: Int::from_i64(2), dir: leaf() };
    assert_eq!(json(&node), r#"{"no":{"esq":"folha","valor":"2","dir":"folha"}}"#);
    let back: adt::Arvore = serde_json::from_str(&json(&node)).unwrap();
    assert_eq!(back, node);
    assert_eq!(json(&records::Codigo("c".to_string())), r#""c""#);
    let config = records::Config {
        r#type: "t".to_string(),
        r#match: Int::from_i64(3),
        filho: Box::new(None),
    };
    assert_eq!(json(&config), r#"{"type":"t","match":"3","filho":null}"#);
    let tree = records::Arv::Nodo { v: Int::from_i64(1), filhos: Arc::new(vec![]) };
    assert_eq!(json(&tree), r#"{"nodo":{"v":"1","filhos":[]}}"#);
    // Unused type parameters leave the JSON shape unchanged.
    assert_eq!(json(&records::Opt::<Int>::Nada), r#""nada""#);
    let back: records::Opt<Int> = serde_json::from_str(r#""nada""#).unwrap();
    assert_eq!(back, records::Opt::Nada);
    let marca = records::Marca::<Int> { nome: "x".to_string(), __phantom: std::marker::PhantomData };
    assert_eq!(json(&marca), r#"{"nome":"x"}"#);
    let back: records::Marca<Int> = serde_json::from_str(r#"{"nome":"x"}"#).unwrap();
    assert_eq!(back, marca);
    // Variant names as certified.rs's `lower_camel`.
    assert_eq!(json(&records::Rotulo::Foo_bar), r#""fooBar""#);
    assert_eq!(json(&records::Rotulo::HTTPError), r#""hTTPError""#);
}

#[test]
fn generated_functions_run() {
    let rt = tokio::runtime::Builder::new_current_thread().build().unwrap();
    let left = adt::Arvore::No { esq: leaf(), valor: Int::from_i64(1), dir: leaf() };
    let tree = adt::Arvore::No { esq: Box::new(left), valor: Int::from_i64(2), dir: leaf() };
    assert_eq!(rt.block_on(adt::bind_soma(Ctx::pure(), tree)).unwrap(), Int::from_i64(3));
    let xs = Arc::new(vec![Int::from_i64(1), Int::from_i64(2), Int::from_i64(3)]);
    assert_eq!(rt.block_on(lambdas::bind_f(Ctx::pure(), xs)).unwrap(), Int::from_i64(12));
    let big = rt
        .block_on(arithmetic::bind_g(Ctx::pure(), Int::from_i64(7), Int::from_i64(0)))
        .unwrap();
    assert_eq!(big.to_string(), "12345678901234567890123");
    assert_eq!(
        rt.block_on(arithmetic::bind_g(Ctx::pure(), Int::from_i64(-7), Int::from_i64(2)))
            .unwrap(),
        Int::from_i64(-3)
    );
    assert_eq!(rt.block_on(control::bind_cedo(Ctx::pure(), Int::from_i64(0))).unwrap(), Int::from_i64(7));
    assert_eq!(rt.block_on(control::bind_cedo(Ctx::pure(), Int::from_i64(1))).unwrap(), Int::from_i64(2));
    assert_eq!(
        rt.block_on(control::bind_texto(Ctx::pure(), "b
".to_string())).unwrap(),
        Int::from_i64(2)
    );
    let child = records::Arv::Nodo { v: Int::from_i64(2), filhos: Arc::new(vec![]) };
    let tree = records::Arv::Nodo { v: Int::from_i64(1), filhos: Arc::new(vec![child.clone(), child]) };
    assert_eq!(rt.block_on(records::bind_total(Ctx::pure(), tree)).unwrap(), Int::from_i64(5));
    assert_eq!(rt.block_on(lambdas::bind_usaIgnora(Ctx::pure())).unwrap(), Int::from_i64(1));
}

/// Real recursion through generated code, on the runtime shape the server uses: worker
/// threads with 64 MiB stacks (debug builds need at least 32 MiB for 10,000 levels).
#[test]
fn deep_recursion_reaches_the_limit_without_overflow() {
    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .thread_stack_size(64 * 1024 * 1024)
        .build()
        .unwrap();
    let run = |n: i64| {
        rt.block_on(async move { tokio::spawn(control::bind_loop(Ctx::pure(), Int::from_i64(n))).await })
            .unwrap()
    };
    // loop(9999) is 10,000 nested calls: the limit itself.
    assert_eq!(run(9999).unwrap(), Int::from_i64(0));
    assert!(matches!(run(10_000), Err(AppError::RecursionLimit)));
    assert!(matches!(run(100_000), Err(AppError::RecursionLimit)));
}
"##;
